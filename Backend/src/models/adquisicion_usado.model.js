  referencia_pago: { type: DataTypes.STRING(120), allowNull: true },
  marca: { type: DataTypes.STRING(100), allowNull: true },
  modelo: { type: DataTypes.STRING(100), allowNull: true },
  numero_serie: { type: DataTypes.STRING(120), allowNull: false, unique: true },
