const router = require('express').Router();
const auth = require('../middlewares/auth.middleware');
const controller = require('../controllers/commercial.controller');
const { registrarAuditoria: audit } = require('../middlewares/audit.middleware');
router.use(auth);
const commercial = (req,res,next) => [1,2,3].includes(req.user.id_role) || req.user.area_grants?.some(area => ['inventario','compras'].includes(area)) ? next() : res.status(403).json({message:'Acceso comercial denegado'});
const quote = (req,res,next) => [1,2,3].includes(req.user.id_role) || req.user.area_grants?.some(area => ['inventario','cotizaciones'].includes(area)) ? next() : res.status(403).json({message:'Acceso denegado'});
router.get('/inventory/dashboard', quote, controller.dashboard);
router.get('/inventory/movements', commercial, controller.movements);
router.get('/inventory/locations', commercial, controller.locations);
router.post('/inventory/locations', commercial, audit('crear_ubicacion', 'inventario'), controller.createLocation);
router.put('/inventory/:id/quant', commercial, audit('fijar_existencia', 'inventario'), controller.setQuant);
router.post('/inventory/:id/adjust', commercial, audit('ajustar_stock', 'inventario'), controller.adjust);
router.get('/suppliers', commercial, controller.listSuppliers);
router.post('/suppliers', commercial, audit('crear', 'proveedores'), controller.createSupplier);
router.put('/suppliers/:id', commercial, audit('actualizar', 'proveedores'), controller.updateSupplier);
router.get('/purchases', commercial, controller.listPurchases);
router.post('/purchases', commercial, audit('crear', 'compras'), controller.createPurchase);
router.post('/purchases/:id/void', commercial, audit('anular', 'compras'), controller.voidPurchase);
router.get('/quotes', quote, controller.listQuotes);
router.post('/quotes', quote, audit('crear', 'cotizaciones'), controller.createQuote);
router.patch('/quotes/:id/status', quote, audit('actualizar_estado', 'cotizaciones'), controller.updateQuoteStatus);
router.post('/quotes/:id/convert', quote, audit('convertir', 'cotizaciones'), controller.convertQuote);
module.exports = router;
